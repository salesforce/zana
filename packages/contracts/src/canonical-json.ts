/**
 * Stable JSON encoding for signed cross-process messages. JSON.parse and schema
 * validators may rebuild objects in a different key order, so signatures must
 * never depend on insertion order from an untrusted transport payload.
 */
export function canonicalJson(value: unknown): string {
  if (value === null || typeof value !== 'object') return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(',')}]`;
  const object = value as Record<string, unknown>;
  return `{${Object.keys(object).sort().map((key) => `${JSON.stringify(key)}:${canonicalJson(object[key])}`).join(',')}}`;
}
