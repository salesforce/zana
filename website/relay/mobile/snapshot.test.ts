import { readFileSync } from 'node:fs';
import { expect, it } from 'vitest';

it('ships the identical Connect relay modules in the website-only Docker context', () => {
  for (const file of ['server.mjs', 'protocol.mjs', 'machine-routes.mjs', 'preview-policy.mjs']) {
    const source = readFileSync(new URL(`../../../services/mobile-relay/${file}`, import.meta.url), 'utf8');
    const copy = readFileSync(new URL(`./${file}`, import.meta.url), 'utf8');
    expect(copy, file).toBe('// Generated by scripts/sync-mobile-relay.mjs. Edit services/mobile-relay instead.\n' + source);
  }
});

it('serves the current machine bootstrap installer from Connect', () => {
  const source = readFileSync(new URL('../../../services/machine-bootstrap/install.mjs', import.meta.url), 'utf8');
  expect(readFileSync(new URL('../../connect/host-installer.mjs', import.meta.url), 'utf8')).toBe(source);
});
