/** Keep the public demo on the plugin's artwork, including website-only builds. */
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { stripTypeScriptTypes } from 'node:module';

export const CITY_FILES = ['scene.js', 'theme-scene.js', 'model.ts', 'themes.ts', 'commuters.ts', 'interior.ts', 'interior-scene.ts', 'use-city.ts'];

export async function syncAgentCity(source, destination) {
  if (!existsSync(join(source, 'scene.js'))) {
    if (!existsSync(join(destination, 'scene.js'))) throw new Error('Agent City source and website snapshot are both missing');
    return 'snapshot';
  }
  await mkdir(destination, { recursive: true });
  for (const file of CITY_FILES) {
    const input = await readFile(join(source, file), 'utf8');
    // Erase plugin SDK type imports. The demo has no SDK or host connection.
    const output = (file.endsWith('.ts') ? stripTypeScriptTypes(input) : input).replace(/[ \t]+$/gm, '');
    await writeFile(join(destination, file.replace(/\.ts$/, '.js')), '// Generated by scripts/sync-agent-city.mjs. Edit plugins/agent-city instead.\n' + output);
  }
  const styles = await readFile(join(source, 'styles.ts'), 'utf8');
  const base = styles.match(/\.agent-city\{((?:--zc-[^;]+;)+)/)?.[1];
  const sf = styles.match(/\.agent-city\[data-city-theme=sf\]\{([^}]+)\}/)?.[1];
  if (!base || !sf) throw new Error('Agent City palette was not found');
  await writeFile(join(destination, 'palette.css'), `/* Generated from the Agent City plugin. */\n.agent-city{${base}color-scheme:dark}\n[data-theme='light'] .agent-city{color-scheme:light}\n.agent-city[data-city-theme=sf]{${sf}}\n`);
  return 'synced';
}

const website = join(dirname(fileURLToPath(import.meta.url)), '..');
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  console.log(`sync-agent-city: ${await syncAgentCity(join(website, '../plugins/agent-city'), join(website, 'lib/agent-city'))}`);
}
