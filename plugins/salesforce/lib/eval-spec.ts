/**
 * Scenario suites and `sf agent test` specs. A suite exports to the YAML test
 * spec format (one test case per scenario case); JSON or YAML specs import
 * back as scenario cases. Pure: no node imports, so the server and tests share it.
 */
import type { ConversationMessage, ScenarioCase } from './studio-contract.js';

export const EVAL_SPEC_LIMITS = { bytes: 256_000, cases: 50 } as const;
/** First line of a spec the Studio wrote. Only such files are overwritten. */
export const GENERATED_SPEC_MARKER = '# Generated by Agentforce Studio';

export class EvalSpecError extends Error {
  constructor(message: string) { super(message); }
}

type Outcome = 'pass' | 'fail' | 'inconclusive';
type Yaml = string | null | Yaml[] | { [key: string]: Yaml };

const quote = (value: string) => JSON.stringify(value);

/** The case's checks as one sentence, for `expectedOutcome`. */
function outcomeText(expect: ScenarioCase['expect']): string {
  const parts: string[] = [];
  if (expect.criteria) parts.push(expect.criteria);
  if (expect.contains?.length) parts.push(`The reply mentions ${expect.contains.map(quote).join(', ')}.`);
  return parts.join(' ');
}

/**
 * Org evals replay a final utterance with recorded history. Earlier agent replies
 * are fixed context; only Simulate reruns every response in the conversation.
 */
export function suiteToEvalSpec(cases: readonly ScenarioCase[], meta: { apiName: string; name: string; from: string }, replay: Record<string, ConversationMessage[]> = {}): { text: string; multiTurn: string[] } {
  if (cases.some(c => c.contextVariables?.length)) throw new EvalSpecError('This suite uses preview context overrides. Run it with Simulate; exporting to an org evaluation spec would lose those values.');
  if (cases.some(c => c.expect.maxLatencyMs !== undefined || c.expect.actionChecks?.length || c.expect.forbiddenActions?.length || c.expect.stateChecks?.length)) throw new EvalSpecError('Latency and action-field assertions, forbidden actions and final-state checks currently run in Simulate. Org export would lose those checks.');
  const lines = [
    `${GENERATED_SPEC_MARKER} from ${meta.from}. Edits here are overwritten: change the scenario suite instead.`,
    `name: ${quote(meta.name)}`,
    'subjectType: AGENT',
    `subjectName: ${quote(meta.apiName)}`,
    'testCases:'
  ];
  const multiTurn: string[] = [];
  for (const c of cases) {
    if (c.utterances.length > 1) {
      const history = replay[c.id];
      if (!history || history.length !== (c.utterances.length - 1) * 2 || history.some((t, i) => t.role !== (i % 2 ? 'agent' : 'user') || !t.message || (t.role === 'agent' && !t.topic) || (t.role === 'user' && t.message !== c.utterances[i / 2]))) throw new EvalSpecError(`Run "${c.name}" in Simulate on the saved source first. Complete conversation history and topic evidence are required for a final-turn org replay.`);
      multiTurn.push(c.id);
    }
    lines.push(`  - utterance: ${quote(c.utterances.at(-1) ?? '')}`);
    if (c.utterances.length > 1) {
      lines.push('    conversationHistory:');
      for (const t of replay[c.id]!) {
        lines.push(`      - role: ${t.role}`, `        message: ${quote(t.message)}`);
        if (t.role === 'agent') lines.push(`        topic: ${quote(t.topic!)}`);
      }
    }
    if (c.expect.topic) lines.push(`    expectedTopic: ${quote(c.expect.topic)}`);
    if (c.expect.actions?.length) {
      lines.push('    expectedActions:');
      for (const action of c.expect.actions) lines.push(`      - ${quote(action)}`);
    }
    const outcome = outcomeText(c.expect);
    if (outcome) lines.push(`    expectedOutcome: ${quote(outcome)}`);
  }
  const text = `${lines.join('\n')}\n`;
  if (new TextEncoder().encode(text).length > EVAL_SPEC_LIMITS.bytes) throw new EvalSpecError('The generated eval spec exceeds 256 KB. Split this suite before exporting.');
  return { text, multiTurn };
}

// ---- A small YAML reader: block mappings and lists, plain/quoted scalars, flow lists, | and > blocks ----

const isItem = (body: string) => body === '-' || body.startsWith('- ');
const indentOf = (line: string) => line.length - line.trimStart().length;
const KEY = /^([A-Za-z_][\w.-]*|"(?:[^"\\]|\\.)*"|'(?:[^']|'')*')\s*:(?:\s+(.*))?$/;

function closingQuote(text: string, mark: string): number {
  for (let i = 1; i < text.length; i++) {
    if (mark === '"' && text[i] === '\\') { i++; continue; }
    if (text[i] !== mark) continue;
    if (mark === "'" && text[i + 1] === "'") { i++; continue; }
    return i;
  }
  return -1;
}

function splitFlow(body: string): string[] {
  const items: string[] = [];
  let current = '';
  let mark: string | null = null;
  for (let i = 0; i < body.length; i++) {
    const char = body[i]!;
    if (mark) {
      current += char;
      if (mark === '"' && char === '\\') { current += body[++i] ?? ''; continue; }
      if (char === mark) mark = null;
      continue;
    }
    if (char === '"' || char === "'") mark = char;
    if (char === ',') { items.push(current); current = ''; continue; }
    current += char;
  }
  items.push(current);
  return items.map(item => item.trim()).filter(Boolean);
}

export function yamlScalar(raw: string): Yaml {
  const text = raw.trim();
  if (text.startsWith('"') || text.startsWith("'")) {
    const end = closingQuote(text, text[0]!);
    if (end < 0) throw new EvalSpecError(`Unclosed quote in ${text.slice(0, 40)}`);
    const body = text.slice(0, end + 1);
    if (text[0] === "'") return body.slice(1, -1).replace(/''/g, "'");
    try { return JSON.parse(body) as string; } catch { return body.slice(1, -1); }
  }
  if (text.startsWith('[')) {
    const end = text.lastIndexOf(']');
    if (end < 0) throw new EvalSpecError(`Unclosed list in ${text.slice(0, 40)}`);
    return splitFlow(text.slice(1, end)).map(item => yamlScalar(item));
  }
  const plain = text.replace(/\s+#.*$/, '').trim();
  return plain === '~' || plain === 'null' || plain === '' ? null : plain;
}

class YamlReader {
  private readonly lines: string[];
  constructor(text: string) { this.lines = text.replace(/\r\n?/g, '\n').split('\n'); }

  private skip(i: number): number {
    while (i < this.lines.length && /^\s*(#.*)?$/.test(this.lines[i]!)) i++;
    return i;
  }

  read(): Yaml {
    const start = this.skip(0);
    if (start >= this.lines.length) return null;
    const line = this.lines[start]!;
    if (line.trimStart() === '---') { this.lines[start] = ''; return this.read(); }
    const [value, next] = this.block(start, indentOf(line));
    const rest = this.skip(next);
    if (rest < this.lines.length) throw new EvalSpecError(`Unreadable YAML at line ${rest + 1}.`);
    return value;
  }

  private block(i: number, indent: number): [Yaml, number] {
    return isItem(this.lines[i]!.trimStart()) ? this.list(i, indent) : this.map(i, indent);
  }

  private list(i: number, indent: number): [Yaml[], number] {
    const out: Yaml[] = [];
    for (i = this.skip(i); i < this.lines.length; i = this.skip(i)) {
      const line = this.lines[i]!;
      const body = line.trimStart();
      if (indentOf(line) !== indent || !isItem(body)) break;
      const rest = body.slice(1).trimStart();
      if (!rest) {
        const next = this.skip(i + 1);
        if (next < this.lines.length && indentOf(this.lines[next]!) > indent) {
          const [value, after] = this.block(next, indentOf(this.lines[next]!));
          out.push(value); i = after;
        } else { out.push(null); i++; }
        continue;
      }
      if (KEY.test(rest) && !rest.startsWith('"') && !rest.startsWith("'")) {
        // "- key: value" opens a mapping whose keys sit where "key" starts.
        const at = indent + body.length - rest.length;
        this.lines[i] = ' '.repeat(at) + rest;
        const [value, after] = this.map(i, at);
        out.push(value); i = after;
        continue;
      }
      out.push(yamlScalar(rest)); i++;
    }
    return [out, i];
  }

  private map(i: number, indent: number): [{ [key: string]: Yaml }, number] {
    const out: { [key: string]: Yaml } = {};
    for (i = this.skip(i); i < this.lines.length; i = this.skip(i)) {
      const line = this.lines[i]!;
      const body = line.trimStart();
      if (indentOf(line) !== indent || isItem(body)) break;
      const match = KEY.exec(body);
      if (!match) throw new EvalSpecError(`Unreadable YAML at line ${i + 1}.`);
      const key = String(yamlScalar(match[1]!));
      const rest = (match[2] ?? '').trim();
      if (/^[|>][+-]?\d*\s*(#.*)?$/.test(rest)) {
        let end = i + 1;
        while (end < this.lines.length && (!this.lines[end]!.trim() || indentOf(this.lines[end]!) > indent)) end++;
        const rows = this.lines.slice(i + 1, end);
        const inner = Math.min(...rows.filter(row => row.trim()).map(indentOf), Infinity);
        const texts = rows.map(row => row.slice(Number.isFinite(inner) ? inner : 0));
        while (texts.length && !texts.at(-1)!.trim()) texts.pop();
        out[key] = rest.startsWith('|') ? texts.join('\n') : texts.map(row => row || '\n').join(' ').replace(/ ?\n ?/g, '\n').trim();
        i = end;
        continue;
      }
      if (rest && !rest.startsWith('#')) { out[key] = yamlScalar(rest); i++; continue; }
      const next = this.skip(i + 1);
      const child = next < this.lines.length ? this.lines[next]! : '';
      if (child && (indentOf(child) > indent || (indentOf(child) === indent && isItem(child.trimStart())))) {
        const [value, after] = this.block(next, indentOf(child));
        out[key] = value; i = after;
      } else { out[key] = null; i++; }
    }
    return [out, i];
  }
}

export function readYaml(text: string): Yaml {
  return new YamlReader(text).read();
}

// ---- Import ----

const record = (value: unknown): Record<string, unknown> => value && typeof value === 'object' && !Array.isArray(value) ? value as Record<string, unknown> : {};
const str = (value: unknown) => typeof value === 'string' ? value.trim() : typeof value === 'number' || typeof value === 'boolean' ? String(value) : '';
function list(value: unknown): string[] {
  if (Array.isArray(value)) return value.map(str).filter(Boolean);
  const text = str(value);
  // AiEvaluationDefinition stores action lists as "['A','B']".
  if (/^\[.*\]$/.test(text)) return splitFlow(text.slice(1, -1)).map(item => item.replace(/^['"]|['"]$/g, '').trim()).filter(Boolean);
  return text ? [text] : [];
}

/** AiEvaluationDefinition `expectation` rows: topic_sequence_match, action_sequence_match, bot_response_rating. */
function fromExpectations(rows: unknown): ScenarioCase['expect'] {
  const expect: ScenarioCase['expect'] = {};
  for (const row of Array.isArray(rows) ? rows : [rows]) {
    const { name, expectedValue } = record(row);
    const kind = str(name).toLowerCase();
    if (kind.startsWith('topic')) expect.topic = str(expectedValue);
    else if (kind.startsWith('action')) expect.actions = list(expectedValue);
    else if (kind.includes('response') || kind.includes('outcome')) expect.criteria = str(expectedValue);
  }
  return expect;
}

function caseFrom(value: unknown, index: number): Record<string, unknown> {
  if (typeof value === 'string') return { id: `case-${index + 1}`, name: value.slice(0, 80), utterances: [value], expect: {} };
  const row = record(value);
  const inputs = record(row.inputs);
  const history = Array.isArray(row.conversationHistory)
    ? row.conversationHistory.map(record).filter(turn => str(turn.role).toLowerCase() === 'user').map(turn => str(turn.message ?? turn.text)).filter(Boolean)
    : [];
  const utterances = [...history, ...list(row.utterances ?? row.utterance ?? inputs.utterance ?? row.input)];
  const expect = row.expectation || row.expectations ? fromExpectations(row.expectation ?? row.expectations) : {};
  const topic = str(row.expectedTopic ?? row.topic) || expect.topic;
  const actions = list(row.expectedActions ?? row.actions);
  const criteria = str(row.expectedOutcome ?? row.criteria) || expect.criteria;
  const contains = list(row.contains);
  const name = str(row.name) || (utterances[0] ?? '').slice(0, 80);
  return {
    id: str(row.id) || name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 60) || `case-${index + 1}`,
    name: name || `Case ${index + 1}`,
    utterances,
    expect: {
      ...(topic ? { topic } : {}),
      ...(actions.length ? { actions } : expect.actions?.length ? { actions: expect.actions } : {}),
      ...(contains.length ? { contains } : {}),
      ...(criteria ? { criteria } : {})
    }
  };
}

/**
 * Scenario case rows from a JSON or YAML spec: a scenario suite (`cases`), an
 * `sf agent test` spec (`testCases`), an eval list (`tests`) or bare utterances.
 * Rows still go through parseScenarioCases; ids are made unique here.
 */
export function evalSpecCases(text: string): Array<Record<string, unknown>> {
  if (text.length > EVAL_SPEC_LIMITS.bytes) throw new EvalSpecError('The spec is larger than 256 KB.');
  const trimmed = text.trim();
  if (!trimmed) throw new EvalSpecError('The spec is empty.');
  let parsed: unknown;
  if (trimmed.startsWith('{') || trimmed.startsWith('[')) {
    try { parsed = JSON.parse(trimmed); } catch { throw new EvalSpecError('The spec is not valid JSON.'); }
  } else parsed = readYaml(trimmed);
  const body = record(parsed);
  const rows = Array.isArray(parsed) ? parsed : [body.cases, body.testCases, body.tests, body.utterances].find(Array.isArray);
  if (!rows?.length) throw new EvalSpecError('The spec needs a non-empty cases, testCases, tests or utterances list.');
  if (rows.length > EVAL_SPEC_LIMITS.cases) throw new EvalSpecError(`A spec can hold at most ${EVAL_SPEC_LIMITS.cases} cases.`);
  const seen = new Set<string>();
  return rows.map((row, index) => {
    const parsedCase = Array.isArray(body.cases) && rows === body.cases ? { ...record(row) } : caseFrom(row, index);
    let id = str(parsedCase.id).replace(/[^A-Za-z0-9_.-]/g, '_').slice(0, 80) || `case-${index + 1}`;
    for (let n = 2; seen.has(id); n++) id = `${id.replace(/-\d+$/, '')}-${n}`;
    seen.add(id);
    return { ...parsedCase, id };
  });
}

// ---- Run results ----

const PASS = /^(pass|passed|success|succeeded|true)$/i;
const FAIL = /^(fail|failed|failure|error|false)$/i;

function verdict(value: unknown): Outcome | null {
  if (value === true) return 'pass';
  if (value === false) return 'fail';
  const text = str(value);
  return PASS.test(text) ? 'pass' : FAIL.test(text) ? 'fail' : null;
}

function rowOutcome(value: unknown): Outcome {
  const row = record(value);
  for (const key of ['status', 'result', 'outcome', 'passed', 'success']) {
    const found = verdict(row[key]);
    if (found) return found;
  }
  const checks = [row.testResults, row.evaluations, row.expectations, row.results].find(Array.isArray) as unknown[] | undefined;
  if (!checks?.length) return 'inconclusive';
  const verdicts = checks.map(check => rowOutcome(check));
  return verdicts.includes('fail') ? 'fail' : verdicts.every(item => item === 'pass') ? 'pass' : 'inconclusive';
}

/**
 * One outcome per spec case, by position, from an `sf agent test run-eval`
 * result. Null when the result carries no per-case list.
 */
export function evalCaseOutcomes(result: unknown, count: number): Outcome[] | null {
  const top = record(result);
  for (const holder of [top, record(top.result), record(top.data)]) {
    const rows = [holder.testCases, holder.tests, holder.testResults, holder.results].find(Array.isArray) as unknown[] | undefined;
    if (!rows) continue;
    return Array.from({ length: count }, (_, index) => index < rows.length ? rowOutcome(rows[index]) : 'inconclusive');
  }
  return null;
}
