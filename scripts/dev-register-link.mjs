#!/usr/bin/env node
/**
 * `pnpm dev:register-link` / `pnpm dev:unregister-link` — macOS-only setup that lets
 * clicking a `zana-dev://plugin/...` link reach `pnpm run dev`.
 *
 * macOS routes a URL scheme only to an app whose Info.plist declares it, and the
 * unpackaged dev Electron does not. This script generates a tiny background helper
 * app (an `osacompile`d AppleScript applet with `on open location`) at
 *
 *   ~/Library/Application Support/Zana Dev Link/ZanaDevLink.app
 *
 * that declares `zana-dev`, validates the URL, and runs
 * `<node> <this checkout>/scripts/dev-open-link.mjs <url>` (absolute paths baked in
 * at registration time; re-run after moving the checkout or changing node).
 *
 * If the dev app is running, dev-open-link hands the link to it through the
 * single-instance lock. If not, and `out-dev/main/index.js` exists, it starts the
 * dev app and routes the link once the window is ready. If `out-dev` has never been
 * built, the helper shows a notification ("Run pnpm run dev first") and does nothing.
 *
 * Flags: `--dry-run` prints the plan and writes nothing; `--unregister` removes it.
 * Exit codes: 0 ok (also on non-macOS, where it only prints a message), 1 failure,
 * 2 usage. No network, no sudo.
 *
 * Windows/Linux keep using ZCC_REGISTER_DEV_PROTOCOL=1 in the dev environment.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, lstatSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isCliEntry } from './dev-local.mjs';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const DEV_SCHEME = 'zana-dev';
export const MAX_LINK_LENGTH = 8192;
export const HELPER_DIR_NAME = 'Zana Dev Link';
export const HELPER_APP_NAME = 'ZanaDevLink.app';
export const HELPER_BUNDLE_ID = 'ai.zana.dev-link-helper';
export const MARKER_FILE = '.zana-dev-link-helper';
export const SOURCE_FILE = 'ZanaDevLink.applescript';

const OSACOMPILE = '/usr/bin/osacompile';
const PLUTIL = '/usr/bin/plutil';
const CODESIGN = '/usr/bin/codesign';
const LSREGISTER =
  '/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister';

// Mirrors packages/desktop-contract/src/deep-link.ts (TS, not importable from a plain
// node script): visible ASCII only, plugin routes.
// The helper additionally restricts the scheme to exactly `zana-dev` and the
// character set to what a base64url payload with %XX escapes needs, so the string
// is inert even if it ever reached a shell.
const LINK_PATTERN = /^zana-dev:\/\/plugin\/[a-z0-9-]+(?:\/[a-z0-9-]+)*\/?(?:\?[A-Za-z0-9._~:/?=&%+-]*)?$/i;
export const APPLESCRIPT_ALLOWED_CHARS = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-._~:/?=&%+';

/** Returns null when `link` may be forwarded, else a human-readable reason. */
export function validateDevLink(link) {
  if (typeof link !== 'string' || link.length === 0) return 'empty link';
  if (link.length > MAX_LINK_LENGTH) return 'link is too long';
  if (/\s|[\u0000-\u001f\u007f-\u009f]/.test(link)) return 'link contains whitespace or control characters';
  if (!LINK_PATTERN.test(link)) return `link must look like ${DEV_SCHEME}://plugin/<pluginId>/<route>?d=<payload>`;
  return null;
}

export function helperPaths(home) {
  const dir = join(home, 'Library', 'Application Support', HELPER_DIR_NAME);
  return { dir, app: join(dir, HELPER_APP_NAME), marker: join(dir, MARKER_FILE), source: join(dir, SOURCE_FILE) };
}

function appleScriptString(value) {
  if (typeof value !== 'string' || value.length === 0 || /[\u0000-\u001f\u007f]/.test(value)) {
    throw new Error('refusing path with control characters or empty path');
  }
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

/** AppleScript source of the helper, with absolute paths baked in. */
export function buildAppleScript({ nodePath, scriptPath, buildEntry }) {
  return `-- Generated by scripts/dev-register-link.mjs. Re-run \`pnpm dev:register-link\` to regenerate.
property nodePath : ${appleScriptString(nodePath)}
property scriptPath : ${appleScriptString(scriptPath)}
property buildEntry : ${appleScriptString(buildEntry)}
property allowedChars : ${appleScriptString(APPLESCRIPT_ALLOWED_CHARS)}

on run
	display notification "Handles ${DEV_SCHEME}:// links for pnpm run dev." with title "Zana Dev Link"
end run

on open location theURL
	set theURL to theURL as text
	if (length of theURL) > ${MAX_LINK_LENGTH} or theURL does not start with "${DEV_SCHEME}://plugin/" then
		display notification "Ignored a link that is not a ${DEV_SCHEME} plugin link." with title "Zana Dev Link"
		return
	end if
	repeat with c in (characters of theURL)
		if allowedChars does not contain (c as text) then
			display notification "Ignored a link with unexpected characters." with title "Zana Dev Link"
			return
		end if
	end repeat
	try
		do shell script "/bin/test -f " & quoted form of buildEntry
	on error
		display notification "Run pnpm run dev first." with title "Zana Dev Link"
		return
	end try
	-- The URL was restricted to a shell-inert character set above and is quoted as ONE argument.
	do shell script quoted form of nodePath & " " & quoted form of scriptPath & " " & quoted form of theURL & " >/dev/null 2>&1 &"
end open location
`;
}

/** `plutil` argv lists that turn the compiled applet into a background `zana-dev` handler. */
export function buildPlistEdits(plistPath) {
  return [
    ['-replace', 'CFBundleIdentifier', '-string', HELPER_BUNDLE_ID, plistPath],
    ['-replace', 'CFBundleName', '-string', 'Zana Dev Link', plistPath],
    ['-replace', 'LSUIElement', '-bool', 'true', plistPath],
    [
      '-replace',
      'CFBundleURLTypes',
      '-json',
      JSON.stringify([{ CFBundleURLName: 'Zana Dev Link', CFBundleURLSchemes: [DEV_SCHEME] }]),
      plistPath
    ]
  ];
}

function defaultDeps() {
  return {
    platform: process.platform,
    home: homedir(),
    nodePath: process.execPath,
    repoRoot,
    exec: (command, args) => execFileSync(command, args, { stdio: 'pipe', encoding: 'utf8' }),
    log: (line) => process.stdout.write(`${line}\n`),
    err: (line) => process.stderr.write(`${line}\n`)
  };
}

function resolveDeps(overrides) {
  return { ...defaultDeps(), ...overrides };
}

export function register(options = {}, overrides = {}) {
  const deps = resolveDeps(overrides);
  const dryRun = Boolean(options.dryRun);
  if (deps.platform !== 'darwin') {
    deps.log('dev:register-link is macOS-only. On Windows/Linux set ZCC_REGISTER_DEV_PROTOCOL=1 for pnpm run dev.');
    return 0;
  }
  const paths = helperPaths(deps.home);
  const scriptPath = join(deps.repoRoot, 'scripts', 'dev-open-link.mjs');
  const buildEntry = join(deps.repoRoot, 'out-dev', 'main', 'index.js');
  let source;
  try {
    source = buildAppleScript({ nodePath: deps.nodePath, scriptPath, buildEntry });
  } catch (error) {
    deps.err(`cannot generate helper: ${error.message}`);
    return 1;
  }
  const plist = join(paths.app, 'Contents', 'Info.plist');
  if (dryRun) {
    deps.log(`[dry-run] would write ${paths.marker} and ${paths.source}`);
    deps.log(`[dry-run] would run: ${OSACOMPILE} -o ${paths.app} ${paths.source}`);
    for (const edit of buildPlistEdits(plist)) deps.log(`[dry-run] would run: ${PLUTIL} ${edit.join(' ')}`);
    deps.log(`[dry-run] would run: ${CODESIGN} --force --deep --sign - ${paths.app}`);
    deps.log(`[dry-run] would run: ${LSREGISTER} -f ${paths.app}`);
    deps.log(`[dry-run] helper would run: ${deps.nodePath} ${scriptPath} <${DEV_SCHEME}:// url>`);
    return 0;
  }
  const fileExists = deps.existsSync ?? existsSync;
  if (!fileExists(OSACOMPILE)) {
    deps.err(`${OSACOMPILE} not found; cannot build the helper app on this macOS install.`);
    return 1;
  }
  try {
    mkdirSync(paths.dir, { recursive: true });
    writeFileSync(paths.marker, 'Generated by scripts/dev-register-link.mjs. Safe to remove with pnpm dev:unregister-link.\n');
    writeFileSync(paths.source, source);
    rmSync(paths.app, { recursive: true, force: true });
    deps.exec(OSACOMPILE, ['-o', paths.app, paths.source]);
    for (const edit of buildPlistEdits(plist)) deps.exec(PLUTIL, edit);
    try {
      deps.exec(CODESIGN, ['--force', '--deep', '--sign', '-', paths.app]);
    } catch (error) {
      deps.err(`warning: ad-hoc codesign failed (${firstLine(error)}); macOS may refuse to launch the helper.`);
    }
    deps.exec(LSREGISTER, ['-f', paths.app]);
  } catch (error) {
    deps.err(`registration failed: ${firstLine(error)}`);
    return 1;
  }
  deps.log(`Registered ${paths.app} for ${DEV_SCHEME}://`);
  deps.log('First click on a zana-dev:// link: if macOS asks which app to use, choose ZanaDevLink and tick "always" so it sticks.');
  deps.log('Links open the running dev app, or start it if out-dev is built; otherwise a "Run pnpm run dev first" notification appears.');
  deps.log('Re-run this command after moving the checkout or changing the node binary.');
  return 0;
}

export function unregister(options = {}, overrides = {}) {
  const deps = resolveDeps(overrides);
  const dryRun = Boolean(options.dryRun);
  if (deps.platform !== 'darwin') {
    deps.log('dev:unregister-link is macOS-only; nothing to do.');
    return 0;
  }
  const paths = helperPaths(deps.home);
  const exists = deps.existsSync ?? existsSync;
  if (!exists(paths.dir)) {
    deps.log('Nothing to remove.');
    return 0;
  }
  let stat;
  try {
    stat = lstatSync(paths.dir);
  } catch (error) {
    deps.err(`could not inspect ${paths.dir}: ${firstLine(error)}`);
    return 1;
  }
  if (!stat.isDirectory() || stat.isSymbolicLink() || !exists(paths.marker)) {
    deps.err(`refusing to delete ${paths.dir}: not a plain directory containing ${MARKER_FILE}`);
    return 1;
  }
  if (dryRun) {
    deps.log(`[dry-run] would run: ${LSREGISTER} -u ${paths.app}`);
    deps.log(`[dry-run] would delete ${paths.dir}`);
    return 0;
  }
  try {
    deps.exec(LSREGISTER, ['-u', paths.app]);
  } catch (error) {
    deps.err(`warning: lsregister -u failed (${firstLine(error)}); continuing.`);
  }
  try {
    rmSync(paths.dir, { recursive: true, force: true });
  } catch (error) {
    deps.err(`could not delete ${paths.dir}: ${firstLine(error)}`);
    return 1;
  }
  deps.log(`Removed ${paths.dir}`);
  return 0;
}

function firstLine(error) {
  return String(error?.stderr || error?.message || error).trim().split('\n')[0];
}

export function main(argv = process.argv.slice(2), overrides = {}) {
  const flags = new Set(argv);
  const unknown = argv.filter((arg) => arg !== '--dry-run' && arg !== '--unregister');
  if (unknown.length > 0) {
    process.stderr.write(`unknown argument(s): ${unknown.join(' ')}\nusage: dev-register-link.mjs [--dry-run] [--unregister]\n`);
    return 2;
  }
  const options = { dryRun: flags.has('--dry-run') };
  return flags.has('--unregister') ? unregister(options, overrides) : register(options, overrides);
}

if (isCliEntry(process.argv[1], import.meta.url)) process.exit(main());
