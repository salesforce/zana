import { toTeamSummary, type TeamSummary } from '@zana-ai/zcc-domain/product';

export const CHEAT_SHEET_START = '<!-- squad-cheat-sheet:start (generated by scripts/generate-squad-cheat-sheet.ts; do not edit by hand) -->';
export const CHEAT_SHEET_END = '<!-- squad-cheat-sheet:end -->';

const CLASS_BY_LEVEL: Record<string, string> = { low: 'Routine', medium: 'Standard', high: 'Expert' };

interface BuiltinTeam { id: string; name: string; source?: unknown; orchestratorPersonaId?: string; slots: { personaId: string }[] }
interface BuiltinPersona { id: string; modelLevel?: 'low' | 'medium' | 'high'; roles?: string[]; source?: unknown }

/**
 * Summaries of the BUILT-IN Squads only. `source === 'builtin'` is the filter: user, Project and plugin Squads are
 * dropped even if a store happened to load them, so the cheat sheet never depends on the reader's machine.
 */
export function builtinSummaries(teams: readonly BuiltinTeam[], personas: readonly BuiltinPersona[]): TeamSummary[] {
  const builtinPersonas = new Map(personas.filter((p) => p.source === 'builtin').map((p) => [p.id, p]));
  return teams
    .filter((team) => team.source === 'builtin')
    .map((team) => {
      const summary = toTeamSummary(team as never, (id) => builtinPersonas.get(id) as never);
      return { ...summary, slots: summary.slots.filter((slot) => slot.personaId !== team.orchestratorPersonaId) };
    })
    .filter((summary) => summary.slots.length > 0)
    .sort((a, b) => a.name.localeCompare(b.name));
}

const cell = (value: string) => value.replace(/\|/g, '\\|');

/** The generated block, markers included. Deterministic: sorted by Squad name, roster order inside a Squad. */
export function renderCheatSheet(summaries: readonly TeamSummary[]): string {
  const out: string[] = [CHEAT_SHEET_START, ''];
  for (const team of summaries) {
    out.push(`### ${team.name}`, '', `Squad id: \`${team.id}\`. ${team.description ?? ''}`.trim(), '');
    out.push('| Worker | Level | Runs steps up to Execution class | Names `Required role` accepts |', '| --- | --- | --- | --- |');
    for (const slot of team.slots) {
      const names = [slot.label, ...(slot.roles ?? []), slot.personaId].filter((n): n is string => !!n?.trim());
      const unique = [...new Set(names.map((n) => n.trim()))];
      out.push(`| ${cell(slot.label ?? slot.personaId)} | ${slot.level ?? 'not set'} | ${slot.level ? CLASS_BY_LEVEL[slot.level] : 'any'} | ${unique.map((n) => `\`${cell(n)}\``).join(', ')} |`);
    }
    out.push('');
  }
  out.push(CHEAT_SHEET_END);
  return out.join('\n');
}

/** Replace the generated block inside a page. Throws when the markers are missing so a typo cannot hide drift. */
export function spliceCheatSheet(page: string, block: string): string {
  const start = page.indexOf(CHEAT_SHEET_START);
  const end = page.indexOf(CHEAT_SHEET_END);
  if (start < 0 || end < start) throw new Error('squads-plans.md is missing the squad-cheat-sheet start/end markers');
  return page.slice(0, start) + block + page.slice(end + CHEAT_SHEET_END.length);
}

export function currentBlock(page: string): string | undefined {
  const start = page.indexOf(CHEAT_SHEET_START);
  const end = page.indexOf(CHEAT_SHEET_END);
  return start < 0 || end < start ? undefined : page.slice(start, end + CHEAT_SHEET_END.length);
}
